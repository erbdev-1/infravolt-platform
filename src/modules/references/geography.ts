/**
 * For compound / free-text fields (e.g. Cable Management's "owner" column,
 * which mixes country names with client-entity abbreviations like "DEWA" or
 * "OMAN : PDO") — resolves a country from any recognisable token or known
 * entity name inside the string. Returns undefined rather than guessing when
 * nothing recognisable is present.
 */
export function resolveOwnerCountry(raw: string): string | undefined {
  const normalised = normalise(raw);
  if (!normalised) return undefined;

  for (const [key, value] of Object.entries(COUNTRY_ALIASES)) {
    if (key.includes(" ") && normalised.includes(key)) return value;
  }

  const tokens = normalised.split(/[^\p{L}0-9.]+/u).filter(Boolean);
  for (const token of tokens) {
    if (COUNTRY_ALIASES[token]) return COUNTRY_ALIASES[token];
    if (GULF_ENTITY_ALIASES[token]) return GULF_ENTITY_ALIASES[token];
  }

  return undefined;
}
