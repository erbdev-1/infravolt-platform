export function resolveReferenceLocation(raw: string): ResolvedLocation {
  const key = normalise(raw);
  if (!key) return { kind: "unknown" };

  const turkiye = TURKIYE_ALIASES[key];
  if (turkiye) return { kind: "turkiye", display: turkiye };

  const country = COUNTRY_ALIASES[key];
  if (country) return { kind: "country", display: country };

  return { kind: "unknown" };
}

